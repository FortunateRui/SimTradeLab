def get_plot_modules():
    try:
        import matplotlib
        matplotlib.use("Agg", force=True)
        import matplotlib.pyplot as plt
        from matplotlib.ticker import PercentFormatter
        return plt, PercentFormatter
    except Exception:
        return None, None


def save_trade_chart(rows: List[Dict[str, object]], output_dir: Path) -> None:
    plt, PercentFormatter = get_plot_modules()
    if plt is None:
        print("Skipped charts: matplotlib is unavailable.")
        return
    labels = [str(r["scenario"]) for r in rows]
    win_rates = [parse_float(r.get("win_rate")) or 0.0 for r in rows]
    returns = [parse_float(r.get("total_return")) or 0.0 for r in rows]
    fig, ax = plt.subplots(figsize=(12, 6))
    x = list(range(len(labels)))
    ax.plot(x, win_rates, marker="o", label="Win Rate")
    ax.plot(x, returns, marker="o", label="Total Return")
    ax.set_xticks(x)
    ax.set_xticklabels(labels, rotation=20, ha="right")
    ax.yaxis.set_major_formatter(PercentFormatter(1.0))
    ax.set_title("Trade Performance by Signal Quality")
    ax.set_ylabel("Rate")
    ax.grid(True, linestyle="--", alpha=0.3)
    ax.legend(loc="best")
    fig.tight_layout()
    path = output_dir / "trade_performance_by_quality.png"
    fig.savefig(path, dpi=180)
    plt.close(fig)
    print("Saved: {}".format(path))


def save_single_stock_chart(rows: List[Dict[str, object]], output_dir: Path) -> None:
    plt, PercentFormatter = get_plot_modules()
    if plt is None:
        return
    candidates = [r for r in rows if r.get("selected") == "True"]
    sample = candidates if candidates else rows[:20]
    if not sample:
        return
    labels = [str(r["security"]) for r in sample]
    ret20 = [parse_float(r.get("ret_20d_median")) or 0.0 for r in sample]
    win_rates = [parse_float(r.get("trade_win_rate")) or 0.0 for r in sample]
    fig, ax = plt.subplots(figsize=(max(12, len(labels) * 0.5), 6))
    x = list(range(len(labels)))
    ax.plot(x, ret20, marker="o", label="20D Directional Return Median")
    ax.plot(x, win_rates, marker="o", label="Trade Win Rate")
    ax.set_xticks(x)
    ax.set_xticklabels(labels, rotation=45, ha="right")
    ax.yaxis.set_major_formatter(PercentFormatter(1.0))
    ax.set_title("Single-stock Applicability Candidates" if candidates else "Top Single-stock Applicability Sample")
    ax.set_ylabel("Rate")
    ax.grid(True, linestyle="--", alpha=0.3)
    ax.legend(loc="best")
    fig.tight_layout()
    path = output_dir / "single_stock_applicability.png"
    fig.savefig(path, dpi=180)
    plt.close(fig)
    print("Saved: {}".format(path))


