def completed_trades(trades: Iterable[Dict[str, str]]) -> List[Dict[str, str]]:
    result = []
    for row in trades:
        if not parse_bool(row.get("bought")):
            continue
        if not str(row.get("sell_date", "")).strip():
            continue
        if parse_float(row.get("pnl")) is None:
            continue
        result.append(row)
    return result


def scenario_filter(row: Dict[str, str], scenario: str) -> bool:
    setup = parse_bool(row.get("setup_is_perfect"))
    countdown = parse_bool(row.get("countdown_is_perfect"))
    if scenario == "all":
        return True
    if scenario == "perfect_setup":
        return setup
    if scenario == "perfect_countdown":
        return countdown
    if scenario == "perfect_both":
        return setup and countdown
    return True


def entry_value(row: Dict[str, str]) -> float:
    value = parse_float(row.get("entry_value"))
    if value and value > 0:
        return value
    qty = parse_float(row.get("buy_quantity")) or 0.0
    price = parse_float(row.get("buy_price")) or 0.0
    return qty * price


def max_drawdown_from_pnls(pnls: Sequence[float]) -> float:
    nav = 1.0
    peak = 1.0
    max_dd = 0.0
    for pnl in pnls:
        nav += pnl / INITIAL_CAPITAL
        if nav > peak:
            peak = nav
        dd = (peak - nav) / peak if peak > 0 else 0.0
        max_dd = max(max_dd, dd)
    return max_dd


def sharpe_from_returns(values: Sequence[float]) -> Optional[float]:
    if len(values) < 2:
        return None
    avg = mean(values) or 0.0
    variance = sum((v - avg) * (v - avg) for v in values) / (len(values) - 1)
    std = variance ** 0.5
    if std == 0:
        return None
    return avg / std * (TRADING_DAYS_PER_YEAR ** 0.5)


def summarize_trades(trades: List[Dict[str, str]]) -> List[Dict[str, object]]:
    scenarios = [
        ("all", "All Buy Countdown"),
        ("perfect_setup", "Perfect Setup"),
        ("perfect_countdown", "Perfect Countdown"),
        ("perfect_both", "Perfect Setup + Countdown"),
    ]
    rows: List[Dict[str, object]] = []
    base = completed_trades(trades)
    for key, label in scenarios:
        sample = [r for r in base if scenario_filter(r, key)]
        pnls = [parse_float(r.get("pnl")) or 0.0 for r in sample]
        wins = [p for p in pnls if p > 0]
        losses = [-p for p in pnls if p < 0]
        trade_returns = []
        for row, pnl in zip(sample, pnls):
            ev = entry_value(row)
            if ev > 0:
                trade_returns.append(pnl / ev)
        avg_profit = mean(wins) or 0.0
        avg_loss = mean(losses) or 0.0
        total_pnl = sum(pnls)
        total_return = total_pnl / INITIAL_CAPITAL if INITIAL_CAPITAL > 0 else 0.0
        rows.append({
            "scenario": label,
            "trade_count": len(sample),
            "win_rate": fmt(safe_div(float(len(wins)), float(len(sample))) if sample else None),
            "avg_profit_loss_ratio": fmt(safe_div(avg_profit, avg_loss) if avg_loss > 0 else (math.inf if avg_profit > 0 else None)),
            "total_pnl": fmt(total_pnl, 2),
            "total_return": fmt(total_return),
            "max_drawdown": fmt(max_drawdown_from_pnls(pnls)),
            "sharpe": fmt(sharpe_from_returns(trade_returns)),
        })
    return rows


