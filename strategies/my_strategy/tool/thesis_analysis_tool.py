def liquidity_bucket(row: Dict[str, str]) -> str:
    amount = parse_float(row.get("pre20_avg_amount"))
    if amount is None:
        return "Unknown"
    if amount >= 300_000_000:
        return "High Liquidity"
    if amount <= 50_000_000:
        return "Low Liquidity"
    return "Mid Liquidity"


def volatility_bucket(row: Dict[str, str]) -> str:
    vol = parse_float(row.get("pre20_volatility"))
    if vol is None:
        return "Unknown"
    if vol >= 0.035:
        return "High Volatility"
    if vol <= 0.015:
        return "Low Volatility"
    return "Mid Volatility"


def market_bucket(row: Dict[str, str]) -> str:
    ret = parse_float(row.get("pre20_return"))
    if ret is None:
        return "Unknown"
    if ret > 0.05:
        return "Uptrend"
    if ret < -0.05:
        return "Downtrend"
    return "Sideways"


def quality_bucket(row: Dict[str, str]) -> str:
    setup = parse_bool(row.get("setup_perfect") or row.get("setup_is_perfect"))
    countdown = parse_bool(row.get("perfect") or row.get("countdown_is_perfect"))
    if setup and countdown:
        return "Perfect Setup + Countdown"
    if setup:
        return "Perfect Setup"
    if countdown:
        return "Perfect Countdown"
    return "Non-perfect"


def build_stratified_summary(events: List[Dict[str, str]], trades: List[Dict[str, str]]) -> List[Dict[str, object]]:
    rows: List[Dict[str, object]] = []
    dimensions = [
        ("Market State", market_bucket),
        ("Liquidity", liquidity_bucket),
        ("Volatility", volatility_bucket),
        ("Signal Quality", quality_bucket),
    ]
    trade_by_setup_dt: Dict[Tuple[str, str], List[Dict[str, str]]] = {}
    for trade in completed_trades(trades):
        trade_by_setup_dt.setdefault((trade.get("security", ""), trade.get("setup_completed_at", "")), []).append(trade)

    for dimension, bucket_func in dimensions:
        grouped_events: Dict[str, List[Dict[str, str]]] = {}
        grouped_trades: Dict[str, List[Dict[str, str]]] = {}
        for event in events:
            bucket = bucket_func(event)
            grouped_events.setdefault(bucket, []).append(event)
            related = trade_by_setup_dt.get((event.get("security", ""), event.get("setup_last_dt", "")), [])
            if related:
                grouped_trades.setdefault(bucket, []).extend(related)
        for bucket in sorted(grouped_events.keys()):
            sample_trades = grouped_trades.get(bucket, [])
            pnls = [parse_float(r.get("pnl")) or 0.0 for r in sample_trades]
            wins = [p for p in pnls if p > 0]
            rows.append({
                "dimension": dimension,
                "bucket": bucket,
                "event_count": len(grouped_events[bucket]),
                "trade_count": len(sample_trades),
                "trade_win_rate": fmt(safe_div(float(len(wins)), float(len(sample_trades))) if sample_trades else None),
                "trade_total_pnl": fmt(sum(pnls), 2),
                "trade_max_drawdown": fmt(max_drawdown_from_pnls(pnls)),
            })
    return rows


