def script_dir() -> Path:
    return Path(__file__).resolve().parent


def resolve_path(value: str) -> Path:
    path = Path(value).expanduser()
    if not path.is_absolute():
        path = script_dir() / path
    return path.resolve()


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Generate TD thesis analysis tables and charts.")
    parser.add_argument("run_folder", nargs="?", default=TARGET_RUN_FOLDER)
    return parser.parse_args()


def parse_datetime(value: object) -> Optional[datetime]:
    text = str(value or "").strip()
    if not text:
        return None
    for fmt in ("%Y-%m-%d %H:%M:%S", "%Y-%m-%d", "%Y/%m/%d %H:%M:%S", "%Y/%m/%d"):
        try:
            return datetime.strptime(text, fmt)
        except ValueError:
            continue
    return None


def date_key(value: object) -> str:
    dt = parse_datetime(value)
    return dt.strftime("%Y-%m-%d") if dt else str(value or "")[:10]


def parse_float(value: object) -> Optional[float]:
    text = str(value or "").strip()
    if text == "":
        return None
    try:
        return float(text)
    except ValueError:
        return None


def parse_bool(value: object) -> bool:
    return str(value or "").strip().lower() in {"1", "true", "t", "yes", "y"}


def safe_div(numerator: float, denominator: float) -> Optional[float]:
    if denominator == 0:
        return None
    return numerator / denominator


def mean(values: Sequence[float]) -> Optional[float]:
    return sum(values) / len(values) if values else None


def quantile(values: Sequence[float], q: float) -> Optional[float]:
    if not values:
        return None
    ordered = sorted(values)
    if len(ordered) == 1:
        return ordered[0]
    pos = (len(ordered) - 1) * q
    lo = int(math.floor(pos))
    hi = int(math.ceil(pos))
    if lo == hi:
        return ordered[lo]
    return ordered[lo] * (hi - pos) + ordered[hi] * (pos - lo)


def fmt(value: Optional[float], digits: int = 6) -> str:
    if value is None:
        return ""
    if math.isinf(value):
        return "inf"
    return str(round(value, digits))


def iter_progress(iterable, desc: str = "", total: Optional[int] = None):
    try:
        from tqdm import tqdm  # type: ignore
        return tqdm(iterable, desc=desc, total=total)
    except Exception:
        if desc:
            print("{}...".format(desc))
        return iterable


def make_event_id(row: Dict[str, str]) -> str:
    existing = str(row.get("event_id", "")).strip()
    if existing:
        return existing
    raw = "{}|{}|{}|{}|{}|{}".format(
        row.get("security", ""),
        row.get("datetime", ""),
        row.get("type", ""),
        row.get("direction", ""),
        row.get("setup_last_dt", ""),
        row.get("count", ""),
    )
    return raw.replace(" ", "T").replace(":", "").replace("|", "_").replace(".", "")


