def is_buy_countdown_complete(row: Dict[str, str]) -> bool:
    return row.get("type", "").startswith("BUY_COUNTDOWN_COMPLETE")


def profit_loss_ratio_from_pnls(pnls: Sequence[float]) -> Optional[float]:
    wins = [p for p in pnls if p > 0]
    losses = [-p for p in pnls if p < 0]
    avg_profit = mean(wins) or 0.0
    avg_loss = mean(losses) or 0.0
    if avg_loss > 0:
        return avg_profit / avg_loss
    if avg_profit > 0:
        return math.inf
    return None


def trade_win_rate_from_pnls(pnls: Sequence[float]) -> Optional[float]:
    if not pnls:
        return None
    wins = [p for p in pnls if p > 0]
    return float(len(wins)) / len(pnls)


def split_consistency(
    events: List[Dict[str, str]],
    trades: List[Dict[str, str]],
    outcome_index: Dict[Tuple[str, int], Dict[str, str]],
) -> str:
    if not events:
        return "False"
    ordered_events = sorted(events, key=lambda r: date_key(r.get("datetime", "")))
    mid = len(ordered_events) // 2
    parts = [ordered_events[:mid], ordered_events[mid:]]
    if not parts[0] or not parts[1]:
        return "False"

    event_ok = []
    for part in parts:
        returns = []
        for row in part:
            ret, _, _ = directional_metrics(row, outcome_index, 20)
            if ret is not None:
                returns.append(ret)
        med = quantile(returns, 0.5)
        event_ok.append(med is not None and med > 0)

    ordered_trades = sorted(trades, key=lambda r: date_key(r.get("sell_date") or r.get("datetime", "")))
    if len(ordered_trades) >= 2:
        trade_mid = len(ordered_trades) // 2
        trade_parts = [ordered_trades[:trade_mid], ordered_trades[trade_mid:]]
        trade_ok = []
        for part in trade_parts:
            pnls = [parse_float(r.get("pnl")) or 0.0 for r in part]
            trade_ok.append(sum(pnls) > 0)
    else:
        trade_ok = [False, False]

    return "True" if all(event_ok) and all(trade_ok) else "False"


def build_single_stock_applicability(
    events: List[Dict[str, str]],
    trades: List[Dict[str, str]],
    outcome_index: Dict[Tuple[str, int], Dict[str, str]],
) -> List[Dict[str, object]]:
    buy_events = [row for row in events if is_buy_countdown_complete(row)]
    completed = completed_trades(trades)

    events_by_stock: Dict[str, List[Dict[str, str]]] = {}
    trades_by_stock: Dict[str, List[Dict[str, str]]] = {}
    for row in buy_events:
        events_by_stock.setdefault(row.get("security", ""), []).append(row)
    for row in completed:
        trades_by_stock.setdefault(row.get("security", ""), []).append(row)

    raw_rows: List[Dict[str, object]] = []
    securities = sorted(set(events_by_stock.keys()) | set(trades_by_stock.keys()))
    for security in iter_progress(securities, desc="Building single-stock applicability", total=len(securities)):
        stock_events = events_by_stock.get(security, [])
        stock_trades = trades_by_stock.get(security, [])
        returns: List[float] = []
        mfes: List[float] = []
        maes: List[float] = []
        for event in stock_events:
            ret, mfe, mae = directional_metrics(event, outcome_index, 20)
            if ret is not None:
                returns.append(ret)
            if mfe is not None:
                mfes.append(mfe)
            if mae is not None:
                maes.append(mae)
        pnls = [parse_float(t.get("pnl")) or 0.0 for t in stock_trades]
        pl_ratio = profit_loss_ratio_from_pnls(pnls)
        win_rate = trade_win_rate_from_pnls(pnls)
        row = {
            "security": security,
            "event_count": len(stock_events),
            "completed_trade_count": len(stock_trades),
            "ret_20d_median": quantile(returns, 0.5),
            "mfe_20d_median": quantile(mfes, 0.5),
            "mae_20d_median": quantile(maes, 0.5),
            "trade_win_rate": win_rate,
            "avg_profit_loss_ratio": pl_ratio,
            "max_drawdown": max_drawdown_from_pnls(pnls),
            "execution_rate": safe_div(float(len(stock_trades)), float(len(stock_events))) if stock_events else None,
            "split_consistent": split_consistency(stock_events, stock_trades, outcome_index),
        }
        raw_rows.append(row)

    eligible = [
        row for row in raw_rows
        if int(row["event_count"]) >= SINGLE_STOCK_EVENT_MIN_COUNT
        and int(row["completed_trade_count"]) >= SINGLE_STOCK_TRADE_MIN_COUNT
    ]
    market_ret = quantile([float(r["ret_20d_median"]) for r in eligible if r["ret_20d_median"] is not None], 0.5)
    market_mae = quantile([float(r["mae_20d_median"]) for r in eligible if r["mae_20d_median"] is not None], 0.5)
    market_win = quantile([float(r["trade_win_rate"]) for r in eligible if r["trade_win_rate"] is not None], 0.5)
    market_pl = quantile([
        float(r["avg_profit_loss_ratio"]) for r in eligible
        if r["avg_profit_loss_ratio"] is not None and not math.isinf(float(r["avg_profit_loss_ratio"]))
    ], 0.5)

    output: List[Dict[str, object]] = []
    for row in raw_rows:
        enough_sample = (
            int(row["event_count"]) >= SINGLE_STOCK_EVENT_MIN_COUNT
            and int(row["completed_trade_count"]) >= SINGLE_STOCK_TRADE_MIN_COUNT
        )
        ret_ok = market_ret is not None and row["ret_20d_median"] is not None and float(row["ret_20d_median"]) > market_ret
        mae_ok = market_mae is not None and row["mae_20d_median"] is not None and float(row["mae_20d_median"]) > market_mae
        win_ok = market_win is not None and row["trade_win_rate"] is not None and float(row["trade_win_rate"]) > market_win
        pl_value = row["avg_profit_loss_ratio"]
        pl_ok = market_pl is not None and pl_value is not None and (math.isinf(float(pl_value)) or float(pl_value) > market_pl)
        selected = enough_sample and ret_ok and mae_ok and win_ok and pl_ok and row["split_consistent"] == "True"
        reason_parts = []
        if not enough_sample:
            reason_parts.append("insufficient sample")
        if enough_sample and not ret_ok:
            reason_parts.append("event return not above market median")
        if enough_sample and not mae_ok:
            reason_parts.append("adverse move not better than market median")
        if enough_sample and not (win_ok and pl_ok):
            reason_parts.append("trade quality not above market median")
        if enough_sample and row["split_consistent"] != "True":
            reason_parts.append("subperiod consistency failed")
        output.append({
            "security": row["security"],
            "event_count": row["event_count"],
            "completed_trade_count": row["completed_trade_count"],
            "ret_20d_median": fmt(row["ret_20d_median"]),
            "mfe_20d_median": fmt(row["mfe_20d_median"]),
            "mae_20d_median": fmt(row["mae_20d_median"]),
            "trade_win_rate": fmt(row["trade_win_rate"]),
            "avg_profit_loss_ratio": fmt(row["avg_profit_loss_ratio"]),
            "max_drawdown": fmt(row["max_drawdown"]),
            "execution_rate": fmt(row["execution_rate"]),
            "split_consistent": row["split_consistent"],
            "selected": "True" if selected else "False",
            "applicability_note": "candidate" if selected else "; ".join(reason_parts),
        })

    output.sort(
        key=lambda r: (
            r["selected"] != "True",
            -(parse_float(r.get("ret_20d_median")) or -999.0),
            -(parse_float(r.get("trade_win_rate")) or -999.0),
        )
    )
    return output


